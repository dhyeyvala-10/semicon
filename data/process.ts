/* ---------------- helpers ---------------- */

function ph(
  id: string,
  label: string,
  duration: number,
  waferState?: WaferState,
  machineState?: MachineState,
  camera?: CameraMode,
  caption?: string,
): Phase {
  return { id, label, duration, waferState, machineState, camera, caption };
}

const T = (
  id: string,
  label: string,
  unit: string,
  min: number,
  max: number,
  sample: (c: TelemetryCtx) => number,
  o: Partial<TelemetryDef> = {},
): TelemetryDef => ({ id, label, unit, min, max, sample, kind: 'SIMULATED', decimals: 1, ...o });

const isP = (c: TelemetryCtx, ...ids: string[]) => ids.includes(c.phaseId);
/** progress of the whole stage counted only after phase `id` started */
const after = (c: TelemetryCtx, order: string[], id: string) => order.indexOf(c.phaseId) > order.indexOf(id);

