export function stageDuration(s: Stage): number {
  return s.phases.reduce((a, p) => a + p.duration, 0);
}

export function journeyIndex(id: string): number {
  return JOURNEY.findIndex((s) => s.id === id);
}

export const stageProgressLabel = (id: string) => {
  const i = journeyIndex(id);
  return i < 0 ? '' : `${String(i + 1).padStart(2, '0')} / ${JOURNEY_LENGTH}`;
};

