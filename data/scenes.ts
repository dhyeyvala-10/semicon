export function presetFor(scene: SceneId, variant: string | undefined, mode: string): CameraPreset | undefined {
  const cfg = SCENES[scene];
  const v = variant ? cfg.variants?.[variant] : undefined;
  return (v?.[mode as keyof typeof v] as CameraPreset | undefined) ?? (cfg.presets[mode as keyof typeof cfg.presets] as CameraPreset | undefined);
}

export function modesFor(scene: SceneId, variant: string | undefined): string[] {
  const cfg = SCENES[scene];
  const set = new Set<string>([...Object.keys(cfg.presets), ...Object.keys((variant && cfg.variants?.[variant]) || {})]);
  const order = ['factory', 'machine', 'internal', 'wafer', 'micro', 'transistor', 'data'];
  return order.filter((m) => set.has(m) || m === 'data');
}
